package com.diploma.chinesedictionary.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * Цветовая палитра приложения — "ягодная печать на фарфоре".
 *
 * Концепция:
 *   - Иероглифы и акценты — ягодный красный (#C1121F), как печать художника.
 *   - Голубой (#B3E5FC) — для фоновых акцентов, "Слова дня", выбранных
 *     элементов. Это цвет китайского сине-белого фарфора 青花瓷.
 *   - Глубокий синий (#003566) — для пиньиня и второстепенного текста
 *     (вместо безликого серого — даёт характер).
 *   - Фон — тёплый кремовый, не утомляет глаза.
 *
 * Логика:
 *   - КРАСНЫЙ = главное, на что смотришь (иероглифы, кнопки, бейджи)
 *   - ГОЛУБОЙ = "приглашение", контекст (фон акцентных блоков)
 *   - СИНИЙ = вспомогательная информация (пиньинь, подписи)
 *
 * Имена сохранены прежними (InkBlack, InkMuted...) — менялись только
 * значения, поэтому весь существующий код подхватывает новую палитру
 * без правок.
 */

// === Основные цвета ===

/** Тёплый кремовый — фон экранов. */
val InkPaper = Color(0xFFFFFBF5)

/** Белый — карточки и поднятые поверхности. */
val InkPaperRaised = Color(0xFFFFFFFF)

/** Ягодный красный — главный акцент: иероглифы, кнопки, активные элементы. */
val InkRed = Color(0xFFC1121F)

/** Светлее основного красного — для hover/pressed состояний. */
val InkRedLight = Color(0xFFE63946)

/**
 * Глубокий синий — заголовки и обычный текст.
 * Раньше тут был чёрный (затем тёмно-синий), теперь — насыщенный navy.
 */
val InkBlack = Color(0xFF003566)

/**
 * Серо-синий для пиньиня и подписей.
 * Не чисто серый — благодаря синему оттенку текст выглядит "тёплым"
 * и связанным с общей палитрой.
 */
val InkMuted = Color(0xFF5C7A99)

/** Лёгкий бежевый — разделители, рамки. */
val InkDivider = Color(0xFFEEE3D5)

// === Голубой блок — для акцентных областей ===

/** Ледяной голубой — фон акцентных блоков, "Слова дня", выбранных целей. */
val PorcelainBlue = Color(0xFFB3E5FC)

/** Чуть глубже голубой — для активных состояний на голубых элементах. */
val PorcelainBlueDeep = Color(0xFF81D4FA)

// === Семантические цвета (для бейджей и т.п.) ===

/** HSK бейджи — голубой фон + насыщенный синий текст. */
val HskBadgeBg = PorcelainBlue
val HskBadgeText = InkBlack

/** Бейджи категорий (термин, редкое и т.д.) — бледно-красный фон. */
val CategoryBadgeBg = Color(0xFFFDE0E2)
val CategoryBadgeText = InkRed